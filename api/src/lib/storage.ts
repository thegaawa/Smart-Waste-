import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { createReadStream } from "node:fs";
import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";

import type { Env } from "../env.js";

/**
 * Where report photos live. The database keeps only the storage key
 * (Chapter 3.12: photos in file storage, not in the database).
 *
 * `LocalDiskStorage` is used for development and tests.
 * `R2ObjectStorage` is used in production when Cloudflare R2 env vars are set.
 */
export interface StoredObject {
  stream: Readable;
  size: number;
}

export interface ObjectStorage {
  /** Stores a new object. Keys are unique, so an existing key is an error. */
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  /** Opens an object for streaming, or returns null when it does not exist. */
  open(key: string): Promise<StoredObject | null>;
  /** Removes an object. Missing objects are ignored. */
  delete(key: string): Promise<void>;
}

export type StorageKind = "local" | "r2";

export interface ConfiguredStorage extends ObjectStorage {
  readonly kind: StorageKind;
}

// Keys are generated by the API (never from user input), but stay defensive.
const KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9/_.-]*$/;

export function assertValidStorageKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error(`Invalid storage key: ${key}`);
  }
}

export class LocalDiskStorage implements ConfiguredStorage {
  readonly kind = "local" as const;
  readonly rootDir: string;

  constructor(rootDir: string) {
    this.rootDir = path.resolve(rootDir);
  }

  private pathFor(key: string): string {
    assertValidStorageKey(key);
    const full = path.resolve(this.rootDir, key);
    if (!full.startsWith(this.rootDir + path.sep)) {
      throw new Error(`Storage key escapes the upload directory: ${key}`);
    }
    return full;
  }

  async put(key: string, data: Buffer, _contentType: string): Promise<void> {
    const full = this.pathFor(key);
    await mkdir(path.dirname(full), { recursive: true });
    // "wx" fails if the file already exists, matching the unique-key contract.
    await writeFile(full, data, { flag: "wx" });
  }

  async open(key: string): Promise<StoredObject | null> {
    const full = this.pathFor(key);
    try {
      const info = await stat(full);
      if (!info.isFile()) return null;
      return { stream: createReadStream(full), size: info.size };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }
}

/**
 * Cloudflare R2 (S3-compatible). Photos survive Render free-tier restarts.
 * EU jurisdiction buckets use `https://<accountId>.eu.r2.cloudflarestorage.com`.
 */
export class R2ObjectStorage implements ConfiguredStorage {
  readonly kind = "r2" as const;
  private readonly client: S3Client;
  private readonly bucket: string;

  constructor(options: {
    accountId: string;
    accessKeyId: string;
    secretAccessKey: string;
    bucket: string;
    /** `eu` for European Union jurisdiction buckets; omit for the default endpoint. */
    jurisdiction?: "eu";
  }) {
    const host =
      options.jurisdiction === "eu"
        ? `${options.accountId}.eu.r2.cloudflarestorage.com`
        : `${options.accountId}.r2.cloudflarestorage.com`;
    this.bucket = options.bucket;
    this.client = new S3Client({
      region: "auto",
      endpoint: `https://${host}`,
      credentials: {
        accessKeyId: options.accessKeyId,
        secretAccessKey: options.secretAccessKey,
      },
    });
  }

  async put(key: string, data: Buffer, contentType: string): Promise<void> {
    assertValidStorageKey(key);
    try {
      await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      throw new Error(`Storage key already exists: ${key}`);
    } catch (error) {
      const name = (error as { name?: string }).name;
      if (name !== "NotFound" && name !== "NoSuchKey") {
        // HeadObject throws NotFound when missing; rethrow real errors and "already exists".
        if ((error as Error).message.startsWith("Storage key already exists")) throw error;
        const status = (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode;
        if (status !== 404) throw error;
      }
    }
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: data,
        ContentType: contentType,
      }),
    );
  }

  async open(key: string): Promise<StoredObject | null> {
    assertValidStorageKey(key);
    try {
      const result = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!result.Body) return null;
      const stream = result.Body instanceof Readable ? result.Body : Readable.fromWeb(result.Body as never);
      const size = result.ContentLength ?? 0;
      return { stream, size };
    } catch (error) {
      const name = (error as { name?: string }).name;
      const status = (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode;
      if (name === "NoSuchKey" || name === "NotFound" || status === 404) return null;
      throw error;
    }
  }

  async delete(key: string): Promise<void> {
    assertValidStorageKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/** Local disk unless all R2 credentials are set. */
export function createStorage(env: Env): ConfiguredStorage {
  const accountId = env.R2_ACCOUNT_ID;
  const accessKeyId = env.R2_ACCESS_KEY_ID;
  const secretAccessKey = env.R2_SECRET_ACCESS_KEY;
  const bucket = env.R2_BUCKET;
  if (accountId && accessKeyId && secretAccessKey && bucket) {
    return new R2ObjectStorage({
      accountId,
      accessKeyId,
      secretAccessKey,
      bucket,
      jurisdiction: env.R2_JURISDICTION,
    });
  }
  return new LocalDiskStorage(env.UPLOADS_DIR);
}
